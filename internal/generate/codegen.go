const generatedHeader = "// Code generated by charlemagne. DO NOT EDIT.\n\n"

func writeRPCLayers(dest string, proj Project, pf protoFile) error {
	if err := os.MkdirAll(filepath.Join(dest, "internal", "entity"), 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(dest, "internal", "usecase"), 0o755); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Join(dest, "internal", "server"), 0o755); err != nil {
		return err
	}

	keepEntity := map[string]struct{}{}
	writtenMsgs := map[string]struct{}{}
	shared := sharedMessages(pf)
	if len(shared) > 0 {
		rel := filepath.Join("internal", "entity", "messages.gen.go")
		keepEntity["messages.gen.go"] = struct{}{}
		if err := writeGo(filepath.Join(dest, rel), renderMessages(pf, shared, writtenMsgs)); err != nil {
			return err
		}
	}

	for _, rpc := range pf.allRPCs() {
		file := snakeName(rpc.Name) + ".gen.go"
		before := len(writtenMsgs)
		msgs := []string{rpc.Request, rpc.Response}
		body := renderMessages(pf, msgs, writtenMsgs)
		if len(writtenMsgs) == before {
			continue
		}
		keepEntity[file] = struct{}{}
		if err := writeGo(filepath.Join(dest, "internal", "entity", file), body); err != nil {
			return err
		}

		stub := filepath.Join(dest, "internal", "usecase", snakeName(rpc.Name)+".go")
		if _, err := os.Stat(stub); os.IsNotExist(err) {
			if err := writeGo(stub, renderUsecaseStub(proj, rpc)); err != nil {
				return err
			}
		} else if err != nil {
			return err
		}
	}

	if err := pruneGenFiles(filepath.Join(dest, "internal", "entity"), keepEntity); err != nil {
		return err
	}

	if err := writeGo(filepath.Join(dest, "internal", "usecase", "rpc.gen.go"), renderRPCInterface(proj, pf)); err != nil {
		return err
	}
	if err := writeGo(filepath.Join(dest, "internal", "server", "grpc.gen.go"), renderGRPCServer(proj, pf)); err != nil {
		return err
	}
	return nil
}

func sharedMessages(pf protoFile) []string {
	used := map[string]struct{}{}
	for _, rpc := range pf.allRPCs() {
		collectRefs(pf, rpc.Request, used)
		collectRefs(pf, rpc.Response, used)
	}
	rpcOwned := map[string]struct{}{}
	for _, rpc := range pf.allRPCs() {
		rpcOwned[rpc.Request] = struct{}{}
		rpcOwned[rpc.Response] = struct{}{}
	}
	var names []string
	for name := range used {
		if _, owned := rpcOwned[name]; owned {
			continue
		}
		if _, ok := pf.Messages[name]; ok {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names
}

func collectRefs(pf protoFile, name string, used map[string]struct{}) {
	msg, ok := pf.Messages[name]
	if !ok {
		return
	}
	if _, seen := used[name]; seen {
		return
	}
	used[name] = struct{}{}
	for _, f := range msg.Fields {
		if f.Message {
			t := strings.TrimPrefix(f.GoType, "[]")
			if strings.HasPrefix(t, "map[") {
				if i := strings.Index(t, "]"); i >= 0 {
					t = t[i+1:]
				}
			}
			collectRefs(pf, t, used)
		}
	}
}

func renderMessages(pf protoFile, names []string, written map[string]struct{}) string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("package entity\n\n")
	b.WriteString("import pb \"" + pf.GoImport + "\"\n\n")
	for _, name := range names {
		if _, ok := written[name]; ok {
			continue
		}
		msg, ok := pf.Messages[name]
		if !ok {
			msg = protoMessage{Name: name}
		}
		written[name] = struct{}{}
		writeMessage(&b, msg)
	}
	return b.String()
}

func writeMessage(b *strings.Builder, msg protoMessage) {
	goName := exportedIdent(msg.Name)
	b.WriteString("type " + goName + " struct {\n")
	for _, f := range msg.Fields {
		b.WriteString("\t" + f.GoName + " " + f.GoType + " `json:\"" + f.JSONName + "\"`\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("func " + goName + "FromProto(in *pb." + goName + ") " + goName + " {\n")
	b.WriteString("\tif in == nil {\n\t\treturn " + goName + "{}\n\t}\n")
	if len(msg.Fields) == 0 {
		b.WriteString("\treturn " + goName + "{}\n}\n\n")
	} else {
		b.WriteString("\tout := " + goName + "{}\n")
		for _, f := range msg.Fields {
			writeFromField(b, f)
		}
		b.WriteString("\treturn out\n}\n\n")
	}

	b.WriteString("func (m " + goName + ") ToProto() *pb." + goName + " {\n")
	b.WriteString("\tout := &pb." + goName + "{}\n")
	for _, f := range msg.Fields {
		writeToField(b, f)
	}
	b.WriteString("\treturn out\n}\n\n")
}

func writeFromField(b *strings.Builder, f protoField) {
	getter := "in.Get" + f.GoName + "()"
	switch {
	case f.Repeated && f.Message:
		elem := strings.TrimPrefix(f.GoType, "[]")
		b.WriteString("\tfor _, item := range " + getter + " {\n")
		b.WriteString("\t\tout." + f.GoName + " = append(out." + f.GoName + ", " + elem + "FromProto(item))\n")
		b.WriteString("\t}\n")
	case f.Map && f.Message:
		val := f.GoType[strings.Index(f.GoType, "]")+1:]
		b.WriteString("\tif src := " + getter + "; src != nil {\n")
		b.WriteString("\t\tout." + f.GoName + " = make(" + f.GoType + ", len(src))\n")
		b.WriteString("\t\tfor k, v := range src {\n")
		b.WriteString("\t\t\tout." + f.GoName + "[k] = " + val + "FromProto(v)\n")
		b.WriteString("\t\t}\n\t}\n")
	case f.Message && !f.Repeated && !f.Map:
		b.WriteString("\tout." + f.GoName + " = " + f.GoType + "FromProto(" + getter + ")\n")
	default:
		b.WriteString("\tout." + f.GoName + " = " + getter + "\n")
	}
}

func writeToField(b *strings.Builder, f protoField) {
	switch {
	case f.Repeated && f.Message:
		b.WriteString("\tfor _, item := range m." + f.GoName + " {\n")
		b.WriteString("\t\tout." + f.GoName + " = append(out." + f.GoName + ", item.ToProto())\n")
		b.WriteString("\t}\n")
	case f.Map && f.Message:
		b.WriteString("\tif m." + f.GoName + " != nil {\n")
		b.WriteString("\t\tout." + f.GoName + " = make(map[" + f.KeyType + "]*pb." + f.GoType[strings.Index(f.GoType, "]")+1:] + ", len(m." + f.GoName + "))\n")
		b.WriteString("\t\tfor k, v := range m." + f.GoName + " {\n")
		b.WriteString("\t\t\tout." + f.GoName + "[k] = v.ToProto()\n")
		b.WriteString("\t\t}\n\t}\n")
	case f.Message && !f.Repeated && !f.Map:
		b.WriteString("\tout." + f.GoName + " = m." + f.GoName + ".ToProto()\n")
	default:
		b.WriteString("\tout." + f.GoName + " = m." + f.GoName + "\n")
	}
}

func renderRPCInterface(proj Project, pf protoFile) string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("package usecase\n\n")
	rpcs := pf.allRPCs()
	if len(rpcs) == 0 {
		b.WriteString("// RPC is filled by charlemagne build from proto.\n")
		b.WriteString("type RPC interface{}\n\n")
		b.WriteString("// UnimplementedRPC is a no-op RPC for tests and partial implementations.\n")
		b.WriteString("type UnimplementedRPC struct{}\n")
		return b.String()
	}
	b.WriteString("import (\n\t\"context\"\n\n\t\"" + proj.Module + "/internal/entity\"\n)\n\n")
	b.WriteString("// RPC is generated from proto services.\n")
	b.WriteString("type RPC interface {\n")
	for _, rpc := range rpcs {
		req := exportedIdent(rpc.Request)
		res := exportedIdent(rpc.Response)
		b.WriteString("\t" + rpc.Name + "(ctx context.Context, in entity." + req + ") (entity." + res + ", error)\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// UnimplementedRPC is a no-op RPC for tests and partial implementations.\n")
	b.WriteString("type UnimplementedRPC struct{}\n\n")
	for _, rpc := range rpcs {
		req := exportedIdent(rpc.Request)
		res := exportedIdent(rpc.Response)
		b.WriteString("func (UnimplementedRPC) " + rpc.Name + "(ctx context.Context, in entity." + req + ") (entity." + res + ", error) {\n")
		b.WriteString("\treturn entity." + res + "{}, nil\n}\n\n")
	}
	return b.String()
}

func renderUsecaseStub(proj Project, rpc protoRPC) string {
	req := exportedIdent(rpc.Request)
	res := exportedIdent(rpc.Response)
	var b strings.Builder
	b.WriteString("package usecase\n\n")
	b.WriteString("import (\n\t\"context\"\n\n\t\"" + proj.Module + "/internal/entity\"\n)\n\n")
	b.WriteString("func (u *useCase) " + rpc.Name + "(ctx context.Context, in entity." + req + ") (entity." + res + ", error) {\n")
	b.WriteString("\treturn entity." + res + "{}, nil\n")
	b.WriteString("}\n")
	return b.String()
}

func renderGRPCServer(proj Project, pf protoFile) string {
	var b strings.Builder
	b.WriteString(generatedHeader)
	b.WriteString("package server\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"context\"\n")
	b.WriteString("\t\"errors\"\n\n")
	b.WriteString("\t\"google.golang.org/grpc\"\n")
	b.WriteString("\t\"google.golang.org/grpc/codes\"\n")
	b.WriteString("\t\"google.golang.org/grpc/status\"\n\n")
	b.WriteString("\t\"" + proj.Module + "/internal/entity\"\n")
	b.WriteString("\t\"" + proj.Module + "/internal/usecase\"\n")
	if len(pf.Services) > 0 && pf.GoImport != "" {
		b.WriteString("\tpb \"" + pf.GoImport + "\"\n")
	}
	b.WriteString(")\n\n")

	b.WriteString("func RegisterGRPC(s *grpc.Server, uc usecase.UseCase) {\n")
	if len(pf.allRPCs()) == 0 {
		b.WriteString("\t_ = s\n\t_ = uc\n}\n")
		return b.String()
	}
	for _, svc := range pf.Services {
		if len(svc.RPCs) == 0 {
			continue
		}
		recv := unexport(svc.Name) + "Server"
		b.WriteString("\tpb.Register" + svc.Name + "Server(s, &" + recv + "{uc: uc})\n")
	}
	b.WriteString("}\n\n")

	for _, svc := range pf.Services {
		if len(svc.RPCs) == 0 {
			continue
		}
		recv := unexport(svc.Name) + "Server"
		b.WriteString("type " + recv + " struct {\n")
		b.WriteString("\tpb.Unimplemented" + svc.Name + "Server\n")
		b.WriteString("\tuc usecase.UseCase\n")
		b.WriteString("}\n\n")
		for _, rpc := range svc.RPCs {
			req := exportedIdent(rpc.Request)
			res := exportedIdent(rpc.Response)
			b.WriteString("func (s *" + recv + ") " + rpc.Name + "(ctx context.Context, req *pb." + req + ") (*pb." + res + ", error) {\n")
			b.WriteString("\tout, err := s.uc." + rpc.Name + "(ctx, entity." + req + "FromProto(req))\n")
			b.WriteString("\tif err != nil {\n\t\treturn nil, grpcStatus(err)\n\t}\n")
			b.WriteString("\treturn out.ToProto(), nil\n}\n\n")
		}
	}

	b.WriteString("func grpcStatus(err error) error {\n")
	b.WriteString("\tif errors.Is(err, entity.ErrNotFound) {\n")
	b.WriteString("\t\treturn status.Error(codes.NotFound, err.Error())\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn status.Error(codes.Internal, \"internal error\")\n")
	b.WriteString("}\n")
	return b.String()
}

func unexport(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func writeGo(path, src string) error {
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("gofmt %s: %w\n%s", path, err, src)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0o644)
}

func pruneGenFiles(dir string, keep map[string]struct{}) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, ent := range entries {
		if ent.IsDir() || !strings.HasSuffix(ent.Name(), ".gen.go") {
			continue
		}
		if _, ok := keep[ent.Name()]; ok {
			continue
		}
		if err := os.Remove(filepath.Join(dir, ent.Name())); err != nil {
			return err
		}
	}
	return nil
}
